export type StringKey = keyof (typeof STRINGS)["en"];

export function translator(language: string | undefined): (key: StringKey) => string {
  const lang = (language ?? "en").split("-")[0];
  const table: Record<string, string> = (STRINGS as any)[lang] ?? STRINGS.en;
  return (key) => table[key] ?? STRINGS.en[key] ?? key;
}

export function numberFormat(language: string | undefined, digits: number): Intl.NumberFormat {
  return new Intl.NumberFormat(language ?? "en", {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  });
}
